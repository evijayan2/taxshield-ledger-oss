import { PRD_DOCUMENT_DATA } from './prdData';

const CLIENT_ID = '489920188108-e86t93j4i2v2442oik5mptpuv4q612h9.apps.googleusercontent.com';
const SCOPES = 'https://www.googleapis.com/auth/documents https://www.googleapis.com/auth/drive.file';

declare global {
  interface Window {
    google?: any;
  }
}

export function requestGoogleAccessToken(): Promise<string> {
  return new Promise((resolve, reject) => {
    if (!window.google || !window.google.accounts || !window.google.accounts.oauth2) {
      reject(new Error("Google Identity Services library is not loaded. Please refresh or check connection."));
      return;
    }

    try {
      const tokenClient = window.google.accounts.oauth2.initTokenClient({
        client_id: CLIENT_ID,
        scope: SCOPES,
        callback: (response: any) => {
          if (response.error) {
            reject(new Error(response.error_description || response.error));
            return;
          }
          if (response.access_token) {
            resolve(response.access_token);
          } else {
            reject(new Error("No access token returned from Google."));
          }
        },
      });

      tokenClient.requestAccessToken({ prompt: '' });
    } catch (err: any) {
      reject(err);
    }
  });
}

export async function createGoogleDocPRD(accessToken: string): Promise<{ docId: string; docUrl: string }> {
  // 1. Create a blank Google Document
  const createDocResponse = await fetch('https://docs.googleapis.com/v1/documents', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: `${PRD_DOCUMENT_DATA.title} - PRD`,
    }),
  });

  if (!createDocResponse.ok) {
    const errJson = await createDocResponse.json().catch(() => ({}));
    throw new Error(`Failed to create Google Doc: ${errJson.error?.message || createDocResponse.statusText}`);
  }

  const doc = await createDocResponse.json();
  const documentId = doc.documentId;

  // 2. Build structured text payload for batchUpdate
  let fullText = `${PRD_DOCUMENT_DATA.title}\n`;
  fullText += `${PRD_DOCUMENT_DATA.subtitle}\n\n`;
  
  fullText += `Document Version: ${PRD_DOCUMENT_DATA.meta.version}\n`;
  fullText += `Target Entity: ${PRD_DOCUMENT_DATA.meta.target}\n`;
  fullText += `Author / Architect: ${PRD_DOCUMENT_DATA.meta.author}\n`;
  fullText += `Tax Jurisdiction Focus: ${PRD_DOCUMENT_DATA.meta.jurisdictionFocus}\n`;
  fullText += `Operating Budget: ${PRD_DOCUMENT_DATA.meta.businessModel}\n\n`;
  fullText += `═══════════════════════════════════════════════════════════════════════════\n\n`;

  for (const section of PRD_DOCUMENT_DATA.sections) {
    fullText += `${section.title}\n`;
    if (section.summary) {
      fullText += `Overview: ${section.summary}\n\n`;
    }

    if (section.paragraphs) {
      for (const p of section.paragraphs) {
        fullText += `${p}\n\n`;
      }
    }

    if (section.bulletGroups) {
      for (const bg of section.bulletGroups) {
        fullText += `${bg.heading}\n`;
        for (const it of bg.items) {
          fullText += `  • ${it}\n`;
        }
        fullText += `\n`;
      }
    }

    if (section.modules) {
      for (const mod of section.modules) {
        fullText += `▶ ${mod.name}\n`;
        for (const feat of mod.features) {
          fullText += `  ✓ ${feat}\n`;
        }
        fullText += `\n`;
      }
    }

    if (section.techPoints) {
      for (const tp of section.techPoints) {
        fullText += `  • ${tp}\n`;
      }
      fullText += `\n`;
    }

    if (section.metrics) {
      for (const met of section.metrics) {
        fullText += `  ★ ${met}\n`;
      }
      fullText += `\n`;
    }

    fullText += `---------------------------------------------------------------------------\n\n`;
  }

  fullText += `\nDocument generated by TaxShield Ledger PRD Engine for Google Docs.\n`;

  // 3. Insert the text into the Google Doc
  const insertTextResponse = await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      requests: [
        {
          insertText: {
            location: {
              index: 1,
            },
            text: fullText,
          },
        },
      ],
    }),
  });

  if (!insertTextResponse.ok) {
    const errJson = await insertTextResponse.json().catch(() => ({}));
    throw new Error(`Failed to populate text into Google Doc: ${errJson.error?.message || insertTextResponse.statusText}`);
  }

  const docUrl = `https://docs.google.com/document/d/${documentId}/edit`;
  return { docId: documentId, docUrl };
}

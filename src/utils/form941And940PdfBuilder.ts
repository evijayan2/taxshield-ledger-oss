import { jsPDF } from 'jspdf';
import type { Form941Worksheet, Form940Worksheet } from 'taxshield-ledger-core';

const fmtUsd = (n: number): string =>
  `$${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/**
 * Generates an IRS Form 941 quarterly reconciliation draft worksheet PDF.
 */
export function generateForm941DraftPdf(ws: Form941Worksheet): jsPDF {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'letter' });
  let y = 48;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(`IRS Form 941 Reconciliation Worksheet (Draft) — ${ws.taxYear} Q${ws.quarter}`, 42, y);
  y += 18;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`Employer: ${ws.employerName}   |   EIN: ${ws.employerEin || 'Pending'}   |   PayStubs: ${ws.payStubCount}`, 42, y);
  y += 22;

  const lines: Array<[string, string, string]> = [
    ['Line 1', 'Number of employees who received wages in quarter', String(ws.line1EmployeesCount)],
    ['Line 2', 'Wages, tips, and other compensation', fmtUsd(ws.line2WagesTipsComp)],
    ['Line 3', 'Federal income tax withheld from wages', fmtUsd(ws.line3FederalIncomeTaxWithheld)],
    ['Line 5a', 'Taxable Social Security wages', fmtUsd(ws.line5aTaxableSsWages)],
    ['Line 5a Tax', 'Social Security tax (6.2% EE + 6.2% ER)', fmtUsd(ws.line5aSsTax)],
    ['Line 5c', 'Taxable Medicare wages', fmtUsd(ws.line5cTaxableMedWages)],
    ['Line 5c Tax', 'Medicare tax (1.45% EE + 1.45% ER)', fmtUsd(ws.line5cMedTax)],
    ['Line 5e', 'Total Social Security and Medicare taxes', fmtUsd(ws.line5eTotalSsMedTaxes)],
    ['Line 6', 'Total taxes before adjustments (Line 3 + Line 5e)', fmtUsd(ws.line6TotalTaxesBeforeAdjustments)],
    ['Line 10', 'Total taxes after adjustments', fmtUsd(ws.line10TotalTaxesAfterAdjustments)],
  ];

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('Line', 42, y);
  doc.text('Description', 110, y);
  doc.text('Amount', 550, y, { align: 'right' });
  y += 6;
  doc.line(42, y, 560, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  for (const [lineNo, desc, val] of lines) {
    doc.text(lineNo, 42, y);
    doc.text(desc, 110, y);
    doc.text(val, 550, y, { align: 'right' });
    y += 18;
  }

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.text('Monthly Liability Schedule (Monthly Depositor / Schedule B Summary)', 42, y);
  y += 16;
  doc.setFont('helvetica', 'normal');
  for (const m of ws.monthlyLiabilityBreakdown) {
    doc.text(`Month ${m.monthIndex} (${m.monthLabel})`, 52, y);
    doc.text(fmtUsd(m.taxLiability), 550, y, { align: 'right' });
    y += 16;
  }

  y += 20;
  doc.setFontSize(8.5);
  doc.setTextColor(100);
  doc.text('Draft workpaper generated by TaxShield Ledger. Verify against official IRS Form 941 before filing.', 42, y);
  return doc;
}

/**
 * Generates an IRS Form 940 annual FUTA reconciliation draft worksheet PDF.
 */
export function generateForm940DraftPdf(ws: Form940Worksheet): jsPDF {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'letter' });
  let y = 48;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(`IRS Form 940 Annual FUTA Worksheet (Draft) — ${ws.taxYear}`, 42, y);
  y += 18;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(
    `Employer: ${ws.employerName}   |   EIN: ${ws.employerEin || 'Pending'}   |   State: ${ws.stateCode}   |   FUTA Rate: ${(ws.futaRate * 100).toFixed(2)}%`,
    42,
    y
  );
  y += 22;

  const lines: Array<[string, string, string]> = [
    ['Line 3', 'Total payments to all employees', fmtUsd(ws.line3TotalPaymentsToAllEmployees)],
    ['Line 4', 'Payments exempt from FUTA (family sole prop/partnership)', fmtUsd(ws.line4ExemptPayments)],
    ['Line 5', `Payments exceeding $${ws.futaWageCap.toLocaleString()} annual cap per employee`, fmtUsd(ws.line5PaymentsExceedingWageCap)],
    ['Line 6', 'Subtotal (Line 4 + Line 5)', fmtUsd(ws.line6SubtotalExempt)],
    ['Line 7', 'Total taxable FUTA wages (Line 3 - Line 6)', fmtUsd(ws.line7TotalTaxableFutaWages)],
    ['Line 8', `FUTA tax before adjustments (${(ws.futaRate * 100).toFixed(2)}%)`, fmtUsd(ws.line8FutaTaxBeforeAdjustments)],
    ['Line 12', 'Total FUTA tax after adjustments', fmtUsd(ws.line12TotalFutaTaxAfterAdjustments)],
  ];

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('Line', 42, y);
  doc.text('Description', 110, y);
  doc.text('Amount', 550, y, { align: 'right' });
  y += 6;
  doc.line(42, y, 560, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  for (const [lineNo, desc, val] of lines) {
    doc.text(lineNo, 42, y);
    doc.text(desc, 110, y);
    doc.text(val, 550, y, { align: 'right' });
    y += 18;
  }

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.text('Quarterly FUTA Tax Liability (Part 5)', 42, y);
  y += 16;
  doc.setFont('helvetica', 'normal');
  for (const q of ws.quarterlyLiability) {
    doc.text(`Quarter ${q.quarter} (Q${q.quarter})`, 52, y);
    doc.text(fmtUsd(q.taxLiability), 550, y, { align: 'right' });
    y += 16;
  }

  y += 20;
  doc.setFontSize(8.5);
  doc.setTextColor(100);
  doc.text('Draft workpaper generated by TaxShield Ledger. Verify against official IRS Form 940 before filing.', 42, y);
  return doc;
}
